#!/usr/bin/env python3
"""Generate the hard-float <-> softfp bridge for the ARM (cpu/arm) build.

phoneME's ARM interpreter/JIT/AOT code calls the jvm_fadd()... helpers with the
softfp convention (float in r0, double in r0:r1). Windows ARM C/C++ is
hard-float (s0/d0). So:

  * arm_softfp_rename.h (force-included into every CLDC .cpp except ROMImage*):
      #define jvm_fadd jvm_fadd_hf ...   -> all C++ calls/definitions are hard-float
  * arm_softfp_glue.c (compiled without the rename):
      - A helpers implemented in Interpreter_arm.asm (softfp, keep the plain
        name): jvm_X_hf() wrappers for C++ callers (constant folding, natives).
      - C helpers (defined in C++ as jvm_X_hf): softfp jvm_X() wrappers for the
        interpreter / ROM (AOT) code that imports the plain name.
      - j2mewp_softfp_entry(): maps a jvm_X_hf address to the softfp jvm_X
        (used by the JIT, CodeGenerator_arm.cpp vcall_simple_c_runtime).

Usage: python3 gen_arm_softfp.py   (writes Project/Shared/host/arm_softfp_*.{h,c})
"""
import os

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
HOST = os.path.join(ROOT, 'Project', 'Shared', 'host')

# name: (return, [args], where)  F=jfloat D=jdouble I=jint L=jlong ; A=asm, C=C++
H = {
    'fadd': ('F', 'FF', 'A'), 'fsub': ('F', 'FF', 'A'), 'fmul': ('F', 'FF', 'A'), 'fdiv': ('F', 'FF', 'A'),
    'dadd': ('D', 'DD', 'A'), 'dsub': ('D', 'DD', 'A'), 'dmul': ('D', 'DD', 'A'), 'ddiv': ('D', 'DD', 'A'),
    'fcmpl': ('I', 'FF', 'A'), 'fcmpg': ('I', 'FF', 'A'), 'dcmpl': ('I', 'DD', 'A'), 'dcmpg': ('I', 'DD', 'A'),
    'i2f': ('F', 'I', 'A'), 'i2d': ('D', 'I', 'A'), 'f2i': ('I', 'F', 'A'), 'f2d': ('D', 'F', 'A'),
    'd2i': ('I', 'D', 'A'), 'd2f': ('F', 'D', 'A'),
    'frem': ('F', 'FF', 'C'), 'drem': ('D', 'DD', 'C'),
    'l2f': ('F', 'L', 'C'), 'l2d': ('D', 'L', 'C'), 'f2l': ('L', 'F', 'C'), 'd2l': ('L', 'D', 'C'),
    'f2d_internal': ('D', 'F', 'C'), 'd2f_internal': ('F', 'D', 'C'),
    'dneg': ('D', 'D', 'C'), 'sin': ('D', 'D', 'C'), 'cos': ('D', 'D', 'C'), 'tan': ('D', 'D', 'C'),
    'sqrt': ('D', 'D', 'C'), 'ceil': ('D', 'D', 'C'), 'floor': ('D', 'D', 'C'), 'fabs': ('D', 'D', 'C'),
}
import sys
# thumb2 (cpu/thumb2 port for WP8.0/8.1): every helper is C++ (no asm float code,
# no ARM-mode thunks); only the softfp glue differs -> thumb2_softfp_glue.c.
MODE = sys.argv[1] if len(sys.argv) > 1 else 'arm'
if MODE == 'thumb2':
    H = dict((n, (r, a, 'C')) for n, (r, a, w) in H.items() if not n.endswith('_internal'))

HF = {'F': 'float', 'D': 'double', 'I': 'int', 'L': 'long long'}
SF = {'F': 'int', 'D': 'long long', 'I': 'int', 'L': 'long long'}   # softfp = integer registers

def to_sf(t, v):
    return {'F': 'f2bits(%s)', 'D': 'd2bits(%s)'}.get(t, '%s') % v

def to_hf(t, v):
    return {'F': 'bits2f(%s)', 'D': 'bits2d(%s)'}.get(t, '%s') % v

hdr = ['/* GENERATED by Project/tools/gen_arm_softfp.py - do not edit.',
       ' * Force-included (/FI) into the CLDC VM sources of the ARM build: C/C++ float',
       ' * helpers become hard-float jvm_X_hf; the plain names are the softfp entry',
       ' * points used by generated code (see arm_softfp_glue.c). */',
       '#ifndef J2MEWP_ARM_SOFTFP_RENAME_H', '#define J2MEWP_ARM_SOFTFP_RENAME_H',
       '#define J2MEWP_SOFTFP_GLUE 1']
for n in sorted(H):
    hdr.append('#define jvm_%s jvm_%s_hf' % (n, n))
hdr.append('#endif')

c = ['/* GENERATED by Project/tools/gen_arm_softfp.py - do not edit.',
     ' * hard-float (Windows ARM C) <-> softfp (phoneME ARM generated code) bridge. */',
     '#if defined(_M_ARM)', '#include <string.h>', '',
     'static int f2bits(float f) { int i; memcpy(&i, &f, 4); return i; }',
     'static float bits2f(int i) { float f; memcpy(&f, &i, 4); return f; }',
     'static long long d2bits(double d) { long long i; memcpy(&i, &d, 8); return i; }',
     'static double bits2d(long long i) { double d; memcpy(&d, &i, 8); return d; }', '']
table = []
for n in sorted(H):
    r, args, where = H[n]
    hf_params = ', '.join('%s a%d' % (HF[t], i) for i, t in enumerate(args))
    sf_params = ', '.join('%s a%d' % (SF[t], i) for i, t in enumerate(args))
    sf_types = ', '.join(SF[t] for t in args)
    hf_types = ', '.join(HF[t] for t in args)
    if where == 'A':
        # softfp body in Interpreter_arm.asm; hard-float wrapper for C++.
        # Called through a Thumb thunk (arm_thumb_thunks.asm): link.exe cannot
        # turn a Thumb BL into BLX to ARM code (Release: LNK2013 BRANCH24(T)).
        c.append('extern %s jvm_%s(%s);' % (SF[r], n, sf_types))
        c.append('extern %s j2mewp_t_jvm_%s(%s);' % (SF[r], n, sf_types))
        call = 'j2mewp_t_jvm_%s(%s)' % (n, ', '.join(to_sf(t, 'a%d' % i) for i, t in enumerate(args)))
        c.append('%s jvm_%s_hf(%s) { return %s; }' % (HF[r], n, hf_params, to_hf(r, call)))
    else:
        # hard-float body in C++ (renamed); softfp wrapper for generated code
        c.append('extern %s jvm_%s_hf(%s);' % (HF[r], n, hf_types))
        call = 'jvm_%s_hf(%s)' % (n, ', '.join(to_hf(t, 'a%d' % i) for i, t in enumerate(args)))
        c.append('%s jvm_%s(%s) { return %s; }' % (SF[r], n, sf_params, to_sf(r, call)))
    table.append('  { (void*)jvm_%s_hf, (void*)jvm_%s },' % (n, n))
c += ['', 'static const struct { void* hf; void* sf; } k_softfp[] = {'] + table + ['};', '',
      '/* JIT: address of a jvm_X_hf helper -> softfp entry (others unchanged). */',
      'unsigned char* j2mewp_softfp_entry(unsigned char* f) {',
      '  unsigned i;',
      '  for (i = 0; i < sizeof(k_softfp) / sizeof(k_softfp[0]); i++)',
      '    if (k_softfp[i].hf == (void*)f) return (unsigned char*)k_softfp[i].sf;',
      '  return f;', '}', '#endif', '']

# ---- Thumb -> ARM call thunks --------------------------------------------------
# Windows ARM C/C++ is Thumb-2; the interpreter asm is ARM (A32). link.exe only
# resolves a Thumb BL to a Thumb target, so a direct call from C into the asm
# fails in Release (LNK2013 BRANCH24(T) fixup overflow). Each thunk is one
# "ldr pc, =target" (interworking load, no register touched, lr kept).
#   CALLED_FROM_C: asm functions that C/C++ calls by name; arm_thumb_calls.h
#   (force-included into every ARM C/C++ file) renames those calls to the thunk.
CALLED_FROM_C = ['current_thread_to_primordial']
#   CALLED_FROM_C_FN: same, but only calls are renamed (function-like macro): taking the
#   address (JIT GP table: pointer(GP_ASM, jvm_memcpy)) must still give the ARM code.
#   ENABLE_FAST_MEM_ROUTINES=1 makes C call these asm routines directly; the VS2012/2013
#   linkers (WP8.0/8.1) left that BL in Thumb state -> C000001D on a WP8.0 phone.
CALLED_FROM_C_FN = {'jvm_memcpy': 3, 'jvm_memcmp': 3}
thunks = ['jvm_%s' % n for n in sorted(H) if H[n][2] == 'A'] + CALLED_FROM_C + sorted(CALLED_FROM_C_FN)
asm = ['; GENERATED by Project/tools/gen_arm_softfp.py - do not edit.',
       '; Thumb -> ARM thunks for calls from C/C++ into Interpreter_arm.asm.',
       '\tAREA |.text|, CODE, READONLY, ALIGN=2', '\tTHUMB']
for t in thunks:
    asm += ['\tIMPORT\t%s' % t, '\tEXPORT\tj2mewp_t_%s' % t, '\tALIGN\t4', 'j2mewp_t_%s PROC' % t,
            '\tldr\tpc, =%s' % t, '\tLTORG', '\tENDP', '']
asm.append('\tEND')
calls = ['/* GENERATED by Project/tools/gen_arm_softfp.py - do not edit.',
         ' * Force-included into all ARM C/C++: calls to these ARM-mode asm functions',
         ' * go through Thumb thunks (arm_thumb_thunks.asm). */',
         '#ifndef J2MEWP_ARM_THUMB_CALLS_H', '#define J2MEWP_ARM_THUMB_CALLS_H',
         '#if defined(_M_ARM)']
calls += ['#define %s j2mewp_t_%s' % (n, n) for n in CALLED_FROM_C]
# the macros below also rename the VM's own declarations: declare the ARM routines here
calls += ['#ifdef __cplusplus', 'extern "C" {', '#endif',
          'void* jvm_memcpy(void* dest, const void* src, int n);   /* the ARM code itself (address users) */',
          'int jvm_memcmp(const void* s1, const void* s2, int n);',
          '#ifdef __cplusplus', '}', '#endif']
for n in sorted(CALLED_FROM_C_FN):
    args = ', '.join('a%d' % i for i in range(CALLED_FROM_C_FN[n]))
    calls.append('#define %s(%s) j2mewp_t_%s(%s)' % (n, args, n, args))
calls += ['#endif', '#endif']

if MODE == 'thumb2':
    open(os.path.join(HOST, 'thumb2_softfp_glue.c'), 'w', newline='\n').write('\n'.join(c))
    print('wrote thumb2_softfp_glue.c (%d helpers)' % len(H))
    sys.exit(0)
open(os.path.join(HOST, 'arm_softfp_rename.h'), 'w', newline='\n').write('\n'.join(hdr) + '\n')
open(os.path.join(HOST, 'arm_softfp_glue.c'), 'w', newline='\n').write('\n'.join(c))
open(os.path.join(HOST, 'arm_thumb_thunks.asm'), 'w', newline='\n').write('\n'.join(asm) + '\n')
open(os.path.join(HOST, 'arm_thumb_calls.h'), 'w', newline='\n').write('\n'.join(calls) + '\n')
print('wrote arm_softfp_rename.h, arm_softfp_glue.c (%d helpers), arm_thumb_thunks.asm (%d thunks), arm_thumb_calls.h'
      % (len(H), len(thunks)))
