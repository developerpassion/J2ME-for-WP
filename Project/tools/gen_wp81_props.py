#!/usr/bin/env python3
"""
Derive Shared/jvm/midp_arm_wp81.props (WP8.1 Silverlight, VS2013 v120 toolset)
from the generated Shared/jvm/midp_arm.props (W10M, VS2017 v141):

  * VS2013 has no /experimental:preprocessor (and no C5105) -> dropped;
    the VM's JVM_CHECK macros compile with the classic preprocessor too.
  * no marmasm BuildCustomization in v120 -> Shared/props/armasm_v120.targets,
    and the interpreter object is patched through item metadata instead of the
    J2MEWPPatchArmObj target (which hooks _MARMASM).

Run after gen_midp_sources.py arm (gen_arm_all.sh does it).
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SHARED = os.path.normpath(os.path.join(HERE, "..", "Shared"))
# arch: arm (default) or thumb2 (cpu/thumb2 VM, what WP8.0/8.1 phones really run)
ARCH = sys.argv[1] if len(sys.argv) > 1 else "arm"
SRC = os.path.join(SHARED, "jvm", "midp_%s.props" % ARCH)
DST = os.path.join(SHARED, "jvm", "midp_%s_wp81.props" % ARCH)


def main():
    s = open(SRC, encoding="utf-8").read()
    s = s.replace("<!-- GENERATED by Project/tools/gen_midp_sources.py",
                  "<!-- GENERATED by Project/tools/gen_wp81_props.py from midp_%s.props, itself generated by Project/tools/gen_midp_sources.py" % ARCH, 1)
    s = s.replace("/experimental:preprocessor ", "").replace("/wd5105 ", "")
    s = s.replace('<Import Project="$(VCTargetsPath)\\BuildCustomizations\\marmasm.props" />', "")
    s = re.sub(r'\s*<Target Name="J2MEWPPatchArmObj".*?</Target>', "", s, flags=re.S)
    s = s.replace('<MARMASM Include="$(J2MESharedDir)romgen\\arm\\Interpreter_arm.asm" />',
                  '<MARMASM Include="$(J2MESharedDir)romgen\\arm\\Interpreter_arm.asm"><J2MEWPPatchArmObj>true</J2MEWPPatchArmObj></MARMASM>')
    s = s.replace("</Project>", '  <Import Project="$(J2MESharedDir)props\\armasm_v120.targets" />\n</Project>')
    if "experimental:preprocessor" in s or "marmasm.props" in s:
        sys.exit("gen_wp81_props: unexpected leftovers")
    with open(DST, "w", encoding="utf-8", newline="\n") as f:
        f.write(s)
    print("wrote", DST)


if __name__ == "__main__":
    main()
