"""
Collect CLDC-HI VM sources + host-generated files for a JvmCore static lib.

Run after build_cldc_host.bat. For an arch (x86 now, arm later) it:
  1. copies generated files (jvmconfig.h, incls/, ROMImage_*.cpp, NativesTable.cpp,
     OopMaps.cpp, Interpreter_<arch>.asm ...) to Project/Shared/romgen/<arch>/
  2. writes Project/Shared/jvm/cldc_vm_<arch>.props listing every .cpp that the
     host build linked into the VM library (taken from the product *.obj list).

Usage: python3 gen_jvmcore_sources.py [x86] [host_platform=win32_i386] [flavor=product]
"""
import os, shutil, sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
CLDC = os.path.join(ROOT, 'phoneME_feature', 'cldc')
arch = sys.argv[1] if len(sys.argv) > 1 else 'x86'
host = sys.argv[2] if len(sys.argv) > 2 else 'win32_i386'
flavor = sys.argv[3] if len(sys.argv) > 3 else 'product'
asm_arch = {'x86': 'i386', 'arm': 'thumb2'}[arch]

target = os.path.join(ROOT, 'Project', 'out', 'cldc_host', host, 'target')
gen_src = os.path.join(target, 'generated')
flv_src = os.path.join(target, flavor)
out = os.path.join(ROOT, 'Project', 'Shared', 'romgen', arch)
out_gen = os.path.join(out, 'generated')

# objects that belong to the launcher exe / test harness, not the library
EXCLUDE = {'Main_win32', '_build_pch_visCPP'}

# ---- 1. copy generated files ------------------------------------------------
if os.path.isdir(out):
    shutil.rmtree(out)
shutil.copytree(gen_src, out_gen,
                ignore=shutil.ignore_patterns('Dependencies*', 'ROMLog.txt', 'Dox.tail',
                                              '_build_pch_visCPP.cpp'))
flavor_files = {}
for f in os.listdir(flv_src):
    if f.endswith('.cpp') or f.endswith('.asm'):
        shutil.copy2(os.path.join(flv_src, f), os.path.join(out, f))
        flavor_files[os.path.splitext(f)[0]] = f

# ---- 2. map *.obj -> source ---------------------------------------------------
src_index = {}
for base in ('src/vm', 'src/anilib'):
    for d, _, files in os.walk(os.path.join(CLDC, base)):
        for f in files:
            if f.endswith('.cpp'):
                src_index.setdefault(os.path.splitext(f)[0], os.path.join(d, f))

objs = sorted(os.path.splitext(f)[0] for f in os.listdir(flv_src) if f.endswith('.obj'))
compile_items, asm_items, missing = [], [], []
for o in objs:
    if o in EXCLUDE:
        continue
    if o in flavor_files and flavor_files[o].endswith('.asm'):
        asm_items.append('$(J2MESharedDir)romgen\\%s\\%s' % (arch, flavor_files[o]))
    elif o in flavor_files:
        compile_items.append('$(J2MESharedDir)romgen\\%s\\%s' % (arch, flavor_files[o]))
    elif os.path.exists(os.path.join(out_gen, o + '.cpp')):
        compile_items.append('$(J2MESharedDir)romgen\\%s\\generated\\%s.cpp' % (arch, o))
    elif o in src_index:
        rel = os.path.relpath(src_index[o], os.path.join(ROOT, 'phoneME_feature'))
        compile_items.append('$(PhoneMERoot)' + rel.replace('/', '\\'))
    else:
        missing.append(o)

if missing:
    print('WARNING: no source for', missing)

inc = ['$(J2MESharedDir)romgen\\%s\\generated' % arch] + ['$(PhoneMERoot)cldc\\src\\' + p for p in (
    'vm\\share\\compiler', 'vm\\share\\debugger', 'vm\\share\\handles', 'vm\\share\\memory',
    'vm\\share\\interpreter', 'vm\\share\\isolate', 'vm\\share\\natives', 'vm\\share\\reflection',
    'vm\\share\\runtime', 'vm\\share\\utilities', 'vm\\share\\ROM', 'vm\\share\\verifier',
    'vm\\share\\float', 'vm\\os\\utilities', 'vm\\share\\memoryprofiler', 'vm\\os\\win32', 'midp',
    'vm\\cpu\\arm', 'vm\\cpu\\c', 'vm\\cpu\\i386', 'vm\\cpu\\sh', 'vm\\cpu\\thumb', 'vm\\cpu\\thumb2',
    'anilib\\share', 'anilib\\win32')]

defs = ['J2MEWP_HAS_VM=1', 'WIN32','_WINDOWS', 'PRODUCT', 'HARDWARE_LITTLE_ENDIAN=1', 'HOST_LITTLE_ENDIAN=1',
        'ROMIZING', 'JVM_RELEASE_VERSION="1.1"', 'JVM_BUILD_VERSION="j2mewp"',
        'JVM_NAME="phoneME Feature VM"', '_CRT_SECURE_NO_WARNINGS', '_WINSOCK_DEPRECATED_NO_WARNINGS']

props = os.path.join(ROOT, 'Project', 'Shared', 'jvm', 'cldc_vm_%s.props' % arch)
with open(props, 'w', newline='\r\n') as f:
    f.write('<?xml version="1.0" encoding="utf-8"?>\n')
    f.write('<!-- GENERATED by Project/tools/gen_jvmcore_sources.py (%s, %s, %s). Do not edit. -->\n'
            % (arch, host, flavor))
    f.write('<Project ToolsVersion="4.0" xmlns="http://schemas.microsoft.com/developer/msbuild/2003">\n')
    f.write('  <ImportGroup Label="ExtensionSettings">\n'
            '    <Import Project="$(VCTargetsPath)\\BuildCustomizations\\masm.props" />\n'
            '  </ImportGroup>\n')
    f.write('  <ItemDefinitionGroup>\n    <ClCompile>\n')
    f.write('      <AdditionalIncludeDirectories>%s;%%(AdditionalIncludeDirectories)</AdditionalIncludeDirectories>\n'
            % ';'.join(inc))
    f.write('      <PreprocessorDefinitions>%s;%%(PreprocessorDefinitions)</PreprocessorDefinitions>\n'
            % ';'.join(d.replace('"', '&quot;') for d in defs))
    # /U_DEBUG: the VM is a PRODUCT build even inside a Debug (/MDd) app; Debug.cpp rejects _DEBUG without AZZERT.
    f.write('      <AdditionalOptions>/experimental:preprocessor /wd5105 /U_DEBUG %(AdditionalOptions)</AdditionalOptions>\n')
    f.write('      <DisableSpecificWarnings>4996;4005;4244;4267;4800;4291;4355;4018;4146;4302;4311;4312;4838;4309;%(DisableSpecificWarnings)</DisableSpecificWarnings>\n')
    f.write('    </ClCompile>\n  </ItemDefinitionGroup>\n')
    f.write('  <ItemGroup>\n')
    f.write('    <ClCompile Include="$(J2MESharedDir)host\\jvm_host_vm.cpp" />\n')
    f.write('    <ClCompile Include="$(J2MESharedDir)host\\os_uwp_memory.cpp" />\n')
    for c in compile_items:
        f.write('    <ClCompile Include="%s" />\n' % c)
    f.write('  </ItemGroup>\n  <ItemGroup>\n')
    for a in asm_items:
        f.write('    <MASM Include="%s" />\n' % a)
    f.write('  </ItemGroup>\n')
    f.write('</Project>\n')

print('copied generated ->', out)
print('wrote', props, ':', len(compile_items), 'cpp,', len(asm_items), 'asm')
