#!/bin/sh
# Rebuild Project/Shared/render/lcd_shaders.h from lcd.hlsl (needs fxc from a Windows SDK).
set -e
cd "$(dirname "$0")/../Shared/render"
FXC="/c/Program Files (x86)/Windows Kits/10/bin/10.0.17763.0/x86/fxc.exe"
MSYS2_ARG_CONV_EXCL='*' "$FXC" /nologo /T vs_4_0_level_9_1 /E VS /Vn g_lcd_vs /Fh lcd_vs.h lcd.hlsl
MSYS2_ARG_CONV_EXCL='*' "$FXC" /nologo /T ps_4_0_level_9_1 /E PS /Vn g_lcd_ps /Fh lcd_ps.h lcd.hlsl
{ echo "// GENERATED by Project/tools/make_lcd_shaders.sh from lcd.hlsl. Do not edit."; echo "#pragma once"; cat lcd_vs.h lcd_ps.h; } > lcd_shaders.h
rm -f lcd_vs.h lcd_ps.h
echo "wrote lcd_shaders.h"
